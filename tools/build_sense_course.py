def sent(tl, ko, who=None):
    d = {}
    if who:
        d['who'] = who
    d.update({'tl': tl, 'rd': transliterate(plain(tl)), 'ko': ko})
    return d


def main():
    levels = []
    for i, (title, note, talk, foot, ref) in enumerate(LEVELS, 1):
        lid = f'L{i}'
        levels.append({
            'id': lid,
            'title': title,
            'lessons': [
                {
                    'id': f'{lid}-talk',
                    'title': title,
                    'kind': 'memorize',
                    'video': '',
                    'note': note,
                    'sentences': [sent(tl, ko, who) for who, tl, ko in talk],
                    'footnotes': foot,
                },
                {
                    'id': f'{lid}-ref',
                    'kind': 'ref',
                    'title': f'{title.split(" — ")[-1]} 한눈에',
                    'points': [{'head': h, 'tip': t, 'sentences': [sent(a, b) for a, b in ex]} for h, t, ex in ref],
                },
            ],
        })
    data = {'title': '언어감각 익히기', 'subtitle': '정규과정 · 대화 통째로 외우기 → 참고', 'levels': levels}
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    n = sum(len(l['lessons'][0]['sentences']) for l in levels)
    print(f'{OUT.relative_to(ROOT)} — {len(levels)}급 · 외울 문장 {n}')


if __name__ == '__main__':
    main()
